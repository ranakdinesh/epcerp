import type { Document as Indent } from '../indent-documents/types';
import type { Line as SourceLine } from '../groups/types';
export type Document = Pick<Indent, 'id' | 'project_id' | 'bo_id' | 'group_id' | 'vendor_id' | 'version'> & {
    vendor_available: boolean;
    data: Pick<Indent['data'], 'terms' | 'number' | 'group_name' | 'scope_revision' | 'is_current' | 'sent_date' | 'vendor' | 'lines'>;
};
export type LineInput = {
    line_id: string;
    unit_price: string | null;
    pricing_mode: string;
    line_total: string | null;
    coverage_type: string;
    warranty_months: number | null;
    discount_pct: string;
    tax_pct: string;
    compliant: boolean;
    notes: string;
};
export type QuoteInput = {
    document_id: string;
    amount_mode: string;
    total_amount: string | null;
    reference: string;
    attachment_id: string | null;
    evidence_reference: string;
    document_not_provided: boolean;
    no_document_reason: string;
    received_date: string;
    valid_until: string;
    currency: string;
    freight: string;
    other_charges: string;
    delivery_days: number;
    delivery_terms: string;
    payment_terms: string;
    lines: LineInput[];
};
export type CalcLine = LineInput & {
    quantity: string;
    source: SourceLine;
    base: string | null;
    discount_amount: string | null;
    net: string | null;
    tax_amount: string | null;
    landed: string | null;
    allocated_charges: string | null;
    item_lowest: boolean;
};
export type Calculation = {
    lines: CalcLine[];
    total: string;
    complete: boolean;
    compliant: boolean;
};
export type Attachment = {
    id: string;
    document_id: string;
    filename: string;
    content_type: string;
    byte_size: number;
    sha256: string;
    is_active: boolean;
    created_at: string;
    created_by_id: string;
};
export type Quote = QuoteInput & {
    calculation: Calculation;
    attachment: Attachment | null;
    created_at: string;
    updated_at: string;
    created_by_id: string;
    updated_by_id: string;
    revision: number;
    recorded_at: string;
    recorded_by_id: string;
    reason: string;
};
export type QuoteRecord = {
    project_id: string;
    bo_id: string;
    version: number;
    quotes: Quote[];
    is_active: boolean;
    created_at: string;
    updated_at: string;
    created_by_id: string | null;
    updated_by_id: string | null;
};
export type Comparison = {
    document_id: string;
    amount_mode: string;
    total_amount: string | null;
    group_id: string;
    group_name: string;
    scope_revision: number;
    vendor_id: string;
    vendor: string;
    reference: string;
    total: string;
    eligible: boolean;
    exclusions: string[];
    expired: boolean;
    delivery_days: number;
    payment_terms: string;
    delivery_terms: string;
    lines: CalcLine[];
    rank: number | null;
    suggested: boolean;
    revision: number;
    received_date: string;
    valid_until: string;
    recorded_at: string;
    reason: string;
};
