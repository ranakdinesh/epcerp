// Keep the native repositories on the reviewed SQL used by Go readers during migration.
import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'../..');
const registry={};
for(const area of ['categories','manufacturers','templates','items']){
 const source=fs.readFileSync(path.join(root,`backend/internal/modules/master/adapters/sql/${area}.sql`),'utf8');
 const queries={};
 for(const match of source.matchAll(/-- name: (\w+) :(\w+)\n([\s\S]*?)(?=-- name:|$)/g)){
  const keys=[];
  const named=key=>{if(!keys.includes(key))keys.push(key);return '$'+(keys.indexOf(key)+1);};
  const text=match[3].trim().replace(/sqlc\.(?:n?arg)\((\w+)\)|@(\w+)/g,(_,a,b)=>named(a??b));
  if(!keys.length&&text.includes('$1'))keys.push(match[1]==='ManufacturersHistory'?'subject_id':'id');
  queries[match[1]]={text,keys,mode:match[2]};
 }
 Object.assign(registry,queries);
}
const destination=path.join(root,'frontend/src/server/master/catalogue/sql.ts');
const content='// Generated by scripts/sync-master-catalogue-sql.mjs from the reviewed catalogue SQL.\nexport const catalogueSQL = '+JSON.stringify(registry,null,2)+' as const;\n';
if(process.argv.includes('--check')) {
 if(fs.readFileSync(destination,'utf8')!==content)throw new Error('Native catalogue SQL differs from reviewed source; run the sync script.');
} else fs.writeFileSync(destination,content);
