import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { pathToFileURL } from "node:url";

const base=process.env.EPCERP_FRONTEND_URL??"http://localhost:59092";
const url=new URL(base);
assert.ok(["localhost","127.0.0.1"].includes(url.hostname)&&url.port==="59092","This mutation verifier is restricted to the isolated QA port");
const runtime=process.env.EPCERP_PLAYWRIGHT_MODULE;
const {chromium}=runtime?await import(pathToFileURL(runtime).href):await import("playwright");
const output=process.env.EPCERP_MASTER_QA_OUTPUT??path.join(os.tmpdir(),"epcerp-master-clients-browser");
fs.mkdirSync(output,{recursive:true,mode:0o700});
const browser=await chromium.launch({headless:true,...(process.env.EPCERP_CHROME_EXECUTABLE?{executablePath:process.env.EPCERP_CHROME_EXECUTABLE}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1000},colorScheme:"light"});
context.setDefaultTimeout(15000);context.setDefaultNavigationTimeout(15000);
await context.route("**/*",r=>["localhost","127.0.0.1"].includes(new URL(r.request().url()).hostname)?r.continue():r.abort());
const page=await context.newPage(),errors=[];
page.on("pageerror",e=>errors.push(e.message));page.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
page.on("dialog",d=>d.accept());
let stage="synthetic sign-in";
try {
  await page.goto(`${base}/login?session=expired`);
  await page.locator("#login-identifier").fill("superadmin");
  await page.locator("#login-password").fill(process.env.EPCERP_QA_ADMIN_PASSWORD??"Migration-Test1!");
  await page.locator('button[type="submit"]').click();
  await page.waitForURL(u=>u.pathname==="/dashboard");await page.locator("#desktop-navigation").waitFor();
  stage="Clients screen";
  const loaded=page.waitForResponse(r=>r.url().includes("/api/settings/clients?")&&r.status()===200);
  await page.goto(`${base}/dashboard?screen=clients`);await loaded;
  await page.getByRole("heading",{name:"Client Master",exact:true}).waitFor();
  const title=await page.title();if(title)assert.match(title,/epcERP/);
  assert.match(await page.locator(".go-appbar").innerText(),/epcERP/);
  async function refs(kind,query="") {const r=await context.request.get(`${base}/api/settings/client-references/${kind}${query}`);assert.equal(r.status(),200);return r.json();}
  const types=await refs("client-types"),industries=await refs("industries"),states=await refs("states");
  const type=types.find(v=>v.is_active&&v.name.startsWith("clientqa")),industry=industries.find(v=>v.is_active&&v.name.startsWith("clientqa")),state=states.find(v=>v.is_active&&v.name==="Maharashtra");
  assert.ok(type&&industry&&state,"Seed isolated reference fixtures before browser testing");
  const cities=await refs("cities",`?state_id=${state.id}`),city=cities.find(v=>v.is_active&&v.name.startsWith("clientqa"));assert.ok(city);
  const name=`QA Browser Client ${Date.now()}`;
  stage="create client";
  await page.getByRole("button",{name:"Create client",exact:true}).click();
  let dialog=page.getByRole("dialog");
  await dialog.locator('[name="legal_name"]').fill(name);
  await dialog.getByLabel(/^Client type/).selectOption(type.id);
  await dialog.getByLabel(/^Industry/).selectOption(industry.id);
  await dialog.locator('[name="address_line_1"]').fill("Synthetic QA address");
  const cityLoaded=page.waitForResponse(r=>r.url().includes(`/client-references/cities?state_id=${state.id}`)&&r.status()===200);
  await dialog.getByLabel("State / Union Territory",{exact:true}).fill(state.name);await cityLoaded;
  await dialog.getByLabel("City",{exact:true}).fill(city.name);
  await dialog.locator('[name="postal_code"]').fill("400001");
  await dialog.locator('[name="gstin"]').fill("27AAACW4202F1ZQ");
  await dialog.locator('[name="pan"]').fill("AAACW4202F");
  const created=page.waitForResponse(r=>r.url().endsWith("/api/settings/clients")&&r.request().method()==="POST");
  await dialog.getByRole("button",{name:"Create client",exact:true}).click();
  const creation=await created;assert.equal(creation.status(),201);const client=await creation.json();
  await dialog.waitFor({state:"hidden"});
  await page.getByRole("textbox",{name:"Search clients",exact:true}).fill(name);
  let row=page.getByRole("row").filter({hasText:name});await row.waitFor();
  async function projectClients() {const r=await context.request.get(`${base}/api/projects/assignment-options`);assert.equal(r.status(),200);return (await r.json()).clients;}
  assert.ok((await projectClients()).some(v=>v.id===client.id),"Go projects must see the native client");
  stage="edit client";
  await row.getByRole("button",{name:`Edit ${name}`,exact:true}).click();dialog=page.getByRole("dialog");
  await dialog.getByLabel("Display name",{exact:true}).fill(`${name} updated`);
  const saved=page.waitForResponse(r=>r.url().endsWith(`/api/settings/clients/${client.id}`)&&r.request().method()==="PATCH");
  await dialog.getByRole("button",{name:"Save changes",exact:true}).click();assert.equal((await saved).status(),200);await dialog.waitFor({state:"hidden"});
  row=page.getByRole("row").filter({hasText:`${name} updated`});await row.waitFor();
  stage="client lifecycle";
  const retired=page.waitForResponse(r=>r.url().endsWith(`/clients/${client.id}/deactivate`));
  await row.getByRole("button",{name:`Deactivate ${name} updated`,exact:true}).click();assert.equal((await retired).status(),200);
  await row.getByText("Inactive",{exact:true}).waitFor();assert.ok(!(await projectClients()).some(v=>v.id===client.id));
  const activated=page.waitForResponse(r=>r.url().endsWith(`/clients/${client.id}/activate`));
  await row.getByRole("button",{name:`Activate ${name} updated`,exact:true}).click();assert.equal((await activated).status(),200);
  await row.getByText("Active",{exact:true}).waitFor();assert.ok((await projectClients()).some(v=>v.id===client.id));
  await page.screenshot({path:path.join(output,"clients-desktop.png"),fullPage:false});
  stage="mobile and console";
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(output,"clients-mobile.png"),fullPage:false});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.doesNotMatch(await page.locator("body").innerText(),/Internal Server Error|Application error|Unable to load clients/);
  assert.deepEqual(errors,[]);
  console.log("PASS: synthetic login, Clients listing/create/edit/lifecycle, Go reference selectors, Go project-directory visibility, mobile overflow and browser console.");
} catch(error) {
  console.error(`Clients browser verification failed at ${stage}.`);
  if(error instanceof assert.AssertionError)console.error(error.message);
  await page.screenshot({path:path.join(output,"failure.png"),fullPage:false});process.exitCode=1;
} finally {await browser.close();}
